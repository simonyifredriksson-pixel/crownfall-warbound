/**
 * The markup for an icon.
 * @param name  a key of ICONS; an unknown name renders the fallback glyph
 *              rather than throwing, because an icon is never worth a crash
 * @param cls   extra classes, e.g. 'big' or 'muted'
 */
export function ic(name, cls) {
  const g = ICONS[name] || ICONS.unknown;
  // class `gi`, not `ic`: the nav dock already uses `.ic` for its own wrapper,
  // and one selector meaning two things is how sizing bugs start
  return `<svg class="gi${cls ? ' ' + cls : ''}" viewBox="0 0 24 24" fill-rule="evenodd" aria-hidden="true">${g}</svg>`;
}

