/* Icons.js — the game's icon language.

   Every icon in Crownfall is drawn here, as vector geometry on one 24x24 grid.
   There are no emoji anywhere in the game: emoji are somebody else's art, they
   render differently on every machine, and they instantly read as placeholder.

   THE RULES THAT MAKE THE SET LOOK LIKE ONE SET
     1. One grid. 24x24, with a ~1.6 unit margin, so nothing touches the edge.
     2. Solid shapes, no strokes. A stroke width that reads at 32px disappears
        at 14px; a filled silhouette survives both.
     3. `fill-rule: evenodd`. Interior detail is a HOLE punched in the same
        path, never a lighter shape painted on top — so an icon stays readable
        on any background and inherits any colour.
     4. `currentColor`. An icon is a glyph: the surrounding UI decides its
        colour, exactly as it decides a letter's.
     5. One optional accent layer (`class="a"`, 55% opacity) for the second
        read — a blade's fuller, a shield's boss. Never more than one.

   Usage:  ic('sword')  ->  '<svg class="ic" ...>...</svg>'
   The data tables store the MARKUP, not the name, so every existing
   `${def.icon}` interpolation in the UI renders real art with no call-site
   change.
*/

/* ------------------------------------------------------------- primitives */

const f = n => (Math.round(n * 100) / 100);

/** A closed polygon from [x,y] pairs. */
function poly(pts) {
  return 'M' + pts.map(p => `${f(p[0])} ${f(p[1])}`).join('L') + 'Z';
}

/** A circle as PATH data, so it can punch a hole inside a larger path. */
const K = 0.5523;
function circ(cx, cy, r) {
  const k = f(r * K);
  cx = f(cx); cy = f(cy); r = f(r);
  return `M${cx - r} ${cy}` +
    `C${cx - r} ${cy - k} ${cx - k} ${cy - r} ${cx} ${cy - r}` +
    `C${cx + k} ${cy - r} ${cx + r} ${cy - k} ${cx + r} ${cy}` +
    `C${cx + r} ${cy + k} ${cx + k} ${cy + r} ${cx} ${cy + r}` +
    `C${cx - k} ${cy + r} ${cx - r} ${cy + k} ${cx - r} ${cy}Z`;
}

/** An axis-aligned rectangle as path data. */
const rect = (x, y, w, h) => poly([[x, y], [x + w, y], [x + w, y + h], [x, y + h]]);

/** An n-pointed star. */
function star(n, ro, ri, cx = 12, cy = 12, rot = -Math.PI / 2) {
  const pts = [];
  for (let i = 0; i < n * 2; i++) {
    const r = i % 2 ? ri : ro;
    const a = rot + i * Math.PI / n;
    pts.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return poly(pts);
}

/** A cog with flat-topped teeth. */
function gear(teeth, ro, ri, cx = 12, cy = 12) {
  const pts = [];
  const step = Math.PI * 2 / teeth, w = step * 0.30;
  for (let i = 0; i < teeth; i++) {
    const a = i * step;
    for (const [d, r] of [[-w, ri], [-w * 0.6, ro], [w * 0.6, ro], [w, ri]]) {
      pts.push([cx + Math.cos(a + d) * r, cy + Math.sin(a + d) * r]);
    }
  }
  return poly(pts);
}

/** Concentric rings — a target, a coin edge, a ward. */
function rings(radii, cx = 12, cy = 12) {
  return radii.map(r => circ(cx, cy, r)).join('');
}

